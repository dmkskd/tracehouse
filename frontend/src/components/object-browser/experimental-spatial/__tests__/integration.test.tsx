import { cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { MemoryRouter } from 'react-router-dom';
import type { Capture } from '@tracehouse/core/services/object-browser';
import { captureFixture } from '../../shared/__tests__/captureFixture';
const { browse, collect, read, update, state } = vi.hoisted(() => ({ browse: vi.fn(), collect: vi.fn(), read: vi.fn(), update: vi.fn(), state: { capture: null as Capture | null } }));
vi.mock('../../useObjectCapture', () => ({ useObjectCapture: () => ({ browse, collect, read, capture: state.capture, loading: false, error: null, connected: true }) }));
vi.mock('../../../../hooks/useUrlState', () => ({ useUrlState: () => ({ state: { ob_selected: '' }, update }) }));
import { ObjectBrowserPage } from '../../ObjectBrowserPage';
import { useUserPreferenceStore } from '../../../../stores/userPreferenceStore';
const memory = new Map<string, string>();
vi.stubGlobal('localStorage', { getItem: (k: string) => memory.get(k) ?? null, setItem: (k: string, v: string) => memory.set(k, v), removeItem: (k: string) => memory.delete(k) });
const renderPage = () => render(<MemoryRouter initialEntries={['/objects']}><ObjectBrowserPage /></MemoryRouter>);

describe('spatial catalog integration', () => {
  beforeEach(() => { vi.clearAllMocks();useUserPreferenceStore.setState({ objectDatabaseColumn: false, objectDiagramStyle: 'cards', objectDiagramLines: { route: false, highlight: true, essential: false } }); });
  afterEach(cleanup);
  it('switches renderers without recollecting, preserves selection, and opens the existing focus from spatial tiles', async () => {
    state.capture = captureFixture();
    renderPage();
    const bob = screen.getByRole('button', { name: 'Focus bob' }).closest('.node')!;
    fireEvent.click(bob.querySelector('.node-select')!);
    // Suppressed graph lines must not remove semantic relationships from spatial.
    fireEvent.click(screen.getByRole('button', { name: 'Diagram' }));
    fireEvent.click(screen.getByRole('checkbox', { name: 'Essential lines' }));
    fireEvent.click(screen.getByRole('radio', { name: 'Isometric' }));
    const spatial = await screen.findByRole('region', { name: 'Isometric object catalog' });
    expect(within(spatial).queryByRole('button', { name: 'Reset camera', exact: true })).toBeNull();
    fireEvent.click(within(spatial).getByRole('button', { name: 'Controls', exact: true }));
    const controls = screen.getByRole('dialog', { name: 'Camera controls' });
    expect(within(controls).getByText('Shift-drag or middle-drag')).toBeTruthy();
    fireEvent.keyDown(document, { key: 'Escape' });
    expect(screen.queryByRole('dialog', { name: 'Camera controls' })).toBeNull();
    expect(document.activeElement).toBe(within(spatial).getByRole('button', { name: 'Controls', exact: true }));
    fireEvent.click(within(spatial).getByRole('button', { name: 'Controls', exact: true }));
    fireEvent.click(screen.getByRole('button', { name: 'Reset camera', exact: true }));
    expect(screen.queryByRole('dialog', { name: 'Camera controls' })).toBeNull();
    expect(within(spatial).getByText(/\d+ of \d+ objects shown$/)).toBeTruthy();
    expect(within(spatial).getByRole('heading', { name: 'Privileges by scope' })).toBeTruthy();
    expect(within(spatial).getByText('ON db.with.dots.*')).toBeTruthy();
    expect(spatial.textContent).toContain('Held by analyst');
    expect(within(spatial).getByRole('button', { name: 'Select bob' }).getAttribute('aria-pressed')).toBe('true');
    expect(spatial.querySelector('[data-family=candidate]')).toBeTruthy();
    const payments = within(spatial).getByRole('button', { name: 'Select db.with.dots.payments', exact: true });
    expect(payments.textContent).toContain('needs SET ROLE');
    expect(within(spatial).getByRole('button', { name: 'Select db.with.dots.audit_log', exact: true }).textContent).toContain('revoked');
    const frame = spatial.querySelector('.spatial-scene')!;
    const beforeSelection = frame.getAttribute('style');
    fireEvent.click(payments);
    expect(frame.getAttribute('style')).toBe(beforeSelection);
    expect(spatial.querySelector('path[opacity="1"][stroke-width="2.8"]')).toBeTruthy();
    fireEvent.click(within(spatial).getByRole('button', { name: 'Open object focus ↗' }));
    expect(screen.getByRole('dialog', { name: 'Object focus' })).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: 'Close focus' }));
    fireEvent.click(within(spatial).getByRole('button', { name: 'Diagram', exact: true }));
    expect(screen.queryByRole('radio', { name: 'Cards', exact: true })).toBeNull();
    expect(screen.getByRole('checkbox', { name: 'Essential lines' })).toBeTruthy();
    expect(screen.getByRole('checkbox', { name: 'Highlight on hover' })).toBeTruthy();
    expect(screen.queryByRole('checkbox', { name: 'Route lines' })).toBeNull();
    fireEvent.click(screen.getByRole('radio', { name: 'Graph', exact: true }));
    const restored = screen.getByRole('button', { name: 'Focus db.with.dots.payments', exact: true }).closest('.node')!;
    expect(restored.querySelector('.node-select')!.getAttribute('aria-pressed')).toBe('true');
    expect(browse).toHaveBeenCalledTimes(1);
    expect(read).not.toHaveBeenCalled();
    expect(collect).not.toHaveBeenCalled();
  });
});
